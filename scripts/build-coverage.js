#!/usr/bin/env node

/**
 * Measure where the directory is thin, from the listings themselves.
 *
 * chatgpt-daily-search.md used to carry these numbers typed in by hand. They
 * were measured on 2026-08-27 and were wrong within days -- it said 547
 * listings and 123 websites when there were 628 and 204 -- and the file ended
 * by asking whoever edited it next to please re-measure, which is what a
 * document says when it knows it rots.
 *
 * A brief that reports stale gaps sends the researcher at the wrong problem.
 * So the numbers are measured on every sync instead of being remembered.
 *
 * FILLED IS NOT THE SAME AS ANSWERED. Two boilerplate lines were written onto
 * hundreds of records by the original state import; a listing carrying one has
 * a Cost Notes value and tells a family nothing. They are counted separately,
 * because counting them as filled would hide the gap this file exists to show.
 *
 *     node scripts/build-coverage.js
 */

'use strict';

const fs = require('fs');
const path = require('path');

const DIR  = __dirname;
const DATA = path.join(DIR, '..', 'village-notes', 'data', 'resources.json');
const OUT  = path.join(DIR, 'coverage.md');

// Connecticut has 169 municipalities. Fixed by statute, not by our data.
const CT_TOWNS = 169;

const BOILERPLATE = [
  ['availability', 'Contact the program directly for current openings'],
  ['cost',         'Reduced state-set fee for eligible families in a funded space'],
];

const data = JSON.parse(fs.readFileSync(DATA, 'utf8'));
const rows = data.resources;
const n = rows.length;

const has = v => v !== null && v !== undefined && String(v).trim() !== '';
const pct = k => `${Math.round((100 * k) / n)}%`;

function real(key) {
  const boiler = BOILERPLATE.find(([f]) => f === key);
  return rows.filter(r => {
    if (!has(r[key])) return false;
    if (boiler && String(r[key]).includes(boiler[1])) return false;
    return true;
  }).length;
}

const filled = key => rows.filter(r => has(r[key])).length;
const listed = key => rows.filter(r => (r[key] || []).length).length;

const towns = new Set();
for (const r of rows) {
  if (r.town) towns.add(r.town);
  for (const t of r.townsServed || []) towns.add(t);
}
const townCount = [...towns].filter(t => !/^statewide/i.test(t)).length;

const metrics = [
  ['a website',            filled('website'),      'the single most valuable gap: without a URL nobody can ever re-check the listing'],
  ['operating hours',      filled('hours'),        'the specific promise on the front of the page'],
  ['a real cost note',     real('cost'),           'excludes the state-fee boilerplate'],
  ['a real waitlist note', real('availability'),   'excludes the "contact the program directly" boilerplate'],
  ['a verified date',      filled('lastVerified'), 'without one we cannot tell fresh from forgotten'],
  ['a phone or email',     filled('contact'),      ''],
  ['services tagged',      listed('servicesOffered'), 'what makes a listing findable beyond its one category'],
];

// Where the missing URLs actually are. "424 listings have no website" is a
// number; "every one of them came from the same import, and every record the
// researcher wrote has one" is a work instruction.
const IMPORT_PREFIX = 'Connecticut Office of Early Childhood';
const noSite   = rows.filter(r => !has(r.website));
const fromImport = noSite.filter(r => (r.submittedBy || '').startsWith(IMPORT_PREFIX)).length;
const researched = rows.filter(r => r.submittedBy === 'Village Notes Research');
const researchedWithSite = researched.filter(r => has(r.website)).length;

const byTrack = new Map();
for (const r of rows) {
  const t = r.track || '(no track)';
  const e = byTrack.get(t) || { n: 0, site: 0 };
  e.n += 1;
  if (has(r.website)) e.site += 1;
  byTrack.set(t, e);
}

const width = Math.max(...metrics.map(m => m[0].length));
const table = metrics.map(([label, k, note]) =>
  `  ${label.padEnd(width)}  ${String(k).padStart(4)} / ${n}  ${pct(k).padStart(4)}` +
  (note ? `   ${note}` : '')).join('\n');

const trackTable = [...byTrack.entries()]
  .sort((a, b) => b[1].n - a[1].n)
  .map(([t, e]) => `  ${t.padEnd(22)} ${String(e.n).padStart(4)} listings, ` +
                   `${String(e.site).padStart(3)} with a website ` +
                   `(${Math.round((100 * e.site) / e.n)}%)`).join('\n');

const stamp = new Date().toISOString().slice(0, 10);

fs.writeFileSync(OUT, `# Village Notes — where the directory is thin

**Generated — do not edit this file.** Run \`node scripts/build-coverage.js\`.
Measured from the published listings, so it is never out of date.

\`\`\`
WHERE THE DIRECTORY IS THIN — measured, not remembered.

Measured on ${stamp}. THESE FIGURES EXPIRE. They are recounted from the
published listings on every sync, which is several times a day, and your own
work is what moves them. Do not save any number here as a baseline or carry it
between sessions: read them fresh from this section each time this brief is
given to you, and if you are working from a remembered figure you are working
from a gap that has already moved.

${n} listings across ${townCount} Connecticut towns of 169.

That breadth is real. The depth behind it is the problem:

${table}

A listing can carry a value and still say nothing. Two boilerplate lines were
written onto hundreds of records by the original state import -- "Contact the
program directly for current openings..." and "Reduced state-set fee for
eligible families in a funded space." The counts above exclude both, because
counting them would hide the gap rather than show it. If you replace one with
something real, say so in your report; that is a win. If you cannot find the
real thing, leave the boilerplate rather than paraphrasing it into something
that sounds more specific than what you actually know.

WEBSITE COVERAGE BY TRACK

${trackTable}

WHY THE WEBSITE COLUMN COMES FIRST

A listing with no URL cannot be re-checked by anyone -- not you, not Darice,
not a parent. It is a dead end the day it is written, and it stays out of the
standing source registry forever, so no scheduled re-read will ever reach it.
Every other gap here can be filled later. That one compounds.

AND THE GAP IS NOT WHERE IT LOOKS

${noSite.length} listings have no website. ${fromImport} of them -- \
${fromImport === noSite.length ? 'every single one' : 'most'} -- came from the
one bulk import of Connecticut Office of Early Childhood childcare providers,
which arrived without URLs. Of the ${researched.length} records written by
research, ${researchedWithSite} carry a website: ${Math.round((100 * researchedWithSite) / (researched.length || 1))}%.

So this is not a habit to correct. It is a bounded backfill of a known set,
and the set is licensed childcare providers whose details came from the state.
They are findable: the provider has a page, or the state's own licensing
lookup has a record. Work through them by town, and record Last Verified as
you go so the standing registry starts reaching them.

That is worth more per hour than finding a new listing, because it converts
${fromImport} permanently unverifiable rows into rows that can be maintained.
\`\`\`
`, 'utf8');

console.log(`Wrote ${path.relative(process.cwd(), OUT)}: ${n} listings, ` +
            `${filled('website')} with a website, ${townCount} towns.`);
