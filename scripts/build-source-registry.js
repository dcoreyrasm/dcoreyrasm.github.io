#!/usr/bin/env node

/**
 * Build the standing source registry ChatGPT re-checks on a schedule.
 *
 * Sites publish new programmes continuously, so a directory that only ever
 * runs open web searches keeps rediscovering the same places and missing the
 * new ones. A standing list fixes that -- but a HAND-MAINTAINED list is the
 * exact drift this project has spent its time undoing everywhere else, and it
 * would be wrong the first time a new site was used.
 *
 * So most of it is derived: every domain in the Website field of a listing we
 * already hold is, by definition, a source that produced something. The one
 * part that cannot be derived is a hub that produced no listing -- it leaves
 * no trace in the base -- so those live in source-hubs.txt by hand.
 *
 * Ordered by how long since anything from that domain was verified, oldest
 * first, because "check these sites" is a reading list and "check these sites,
 * these ones first" is a work queue.
 *
 *     node scripts/build-source-registry.js
 */

'use strict';

const fs = require('fs');
const path = require('path');

const DIR  = __dirname;
const DATA = path.join(DIR, '..', 'village-notes', 'data', 'resources.json');
const HUBS = path.join(DIR, 'source-hubs.txt');
const OUT  = path.join(DIR, 'source-registry.md');

const DAY = 24 * 60 * 60 * 1000;

function domainOf(url) {
  try {
    const host = new URL(url).hostname.toLowerCase();
    return host.startsWith('www.') ? host.slice(4) : host;
  } catch (err) {
    return null; // not a URL we can group by; the listing still stands
  }
}

function readHubs() {
  if (!fs.existsSync(HUBS)) return [];
  return fs.readFileSync(HUBS, 'utf8')
    .split('\n')
    .map(line => line.trim())
    .filter(line => line && !line.startsWith('#'))
    .map(line => {
      const [domain, track, note] = line.split('|').map(s => (s || '').trim());
      return { domain, track, note };
    })
    .filter(h => h.domain);
}

const data = JSON.parse(fs.readFileSync(DATA, 'utf8'));
const today = new Date();

// domain -> { listings, tracks, newestVerified }
const byDomain = new Map();
for (const r of data.resources) {
  const domain = r.website && domainOf(r.website);
  if (!domain) continue;
  const entry = byDomain.get(domain) || { listings: 0, tracks: new Set(), verified: null };
  entry.listings += 1;
  if (r.track) entry.tracks.add(r.track);
  if (r.lastVerified && (!entry.verified || r.lastVerified > entry.verified)) {
    entry.verified = r.lastVerified;
  }
  byDomain.set(domain, entry);
}

const rows = [...byDomain.entries()].map(([domain, e]) => ({
  domain,
  listings: e.listings,
  tracks: [...e.tracks].sort().join(', '),
  verified: e.verified,
  age: e.verified ? Math.round((today - new Date(e.verified + 'T00:00:00')) / DAY) : null
}));

// Never verified first -- those are the ones nobody has ever gone back to --
// then oldest, then the domains carrying the most listings.
rows.sort((a, b) => {
  if ((a.age === null) !== (b.age === null)) return a.age === null ? -1 : 1;
  if (a.age !== b.age) return (b.age || 0) - (a.age || 0);
  return b.listings - a.listings;
});

const withSite = data.resources.filter(r => r.website).length;
const total = data.resources.length;
const pct = n => Math.round((100 * n) / total);
const never = rows.filter(r => r.age === null).length;

// The date only, never "N days ago". Age is what orders the list, but printing
// it would change this file every time the clock rolled past midnight, and the
// sync would commit a diff that means nothing. The relative order is unaffected
// by the passage of time -- every age shifts together -- so the queue stays
// right while the file stays still.
const table = rows.map(r => {
  const when = r.verified || 'never';
  return `  ${r.domain.padEnd(32)} ${String(r.listings).padStart(3)}  ${when.padEnd(12)} ${r.tracks}`;
}).join('\n');

const hubs = readHubs();
const hubTable = hubs.map(h =>
  `  ${h.domain.padEnd(26)} ${(h.track || '').padEnd(12)} ${h.note || ''}`).join('\n');

fs.writeFileSync(OUT, `# Village Notes — standing source registry

**Generated — do not edit this file.** Run \`node scripts/build-source-registry.js\`.
The hub list at the bottom comes from \`source-hubs.txt\`, which IS edited by hand.

\`\`\`
STANDING SOURCES — re-read these on a schedule, oldest first.

A site that gave us a listing once will give us another. Programmes open,
close, change their hours and move their deadlines, and none of that reaches
us through an open web search for "Connecticut childcare" -- it reaches us by
going back to the page we read last time.

Work down this list in order. The date is the most recent Last Verified on any
listing from that domain, so the top of the list is what nobody has looked at
for longest. "never" means no listing from that site carries a Last Verified
at all, which is worse than stale: it means we do not know whether it was ever
right.

When you re-read a site, update Last Verified on every listing you confirm,
even when nothing changed. An unchanged listing that was checked today is
worth far more to a family than one that was right in August and might not be
now.

  ${'DOMAIN'.padEnd(32)} ${'N'.padStart(3)}  ${'VERIFIED'.padEnd(12)} TRACKS
${table}

HUBS AND DIRECTORIES — check these every run regardless of the dates above.

These publish new programmes continuously, so they are where a resource we do
not have yet shows up. Most will not become a listing themselves.

${hubTable}

WHAT THIS LIST DOES NOT COVER

Only ${withSite} of ${total} listings (${pct(withSite)}%) carry a Website, so
everything above is built from that third of the directory. The other
${total - withSite} have no URL recorded at all, which means nobody -- not you,
not Darice, not a parent -- can go back and check them. They are permanently
unverifiable in their current state.

So when you deepen an existing listing, recording its Website is worth more
than almost anything else you could add. It is what makes a listing checkable
ever again, and it is what puts the site into this queue.

${never} of the ${rows.length} domains here have never had a Last Verified on
any of their listings. Those sit at the top of the list for a reason: we do
not know whether they were ever right, only that they were right once.
\`\`\`
`, 'utf8');

console.log(`Wrote ${path.relative(process.cwd(), OUT)}: ${rows.length} domains, ` +
            `${hubs.length} hubs, ${never} never verified.`);
