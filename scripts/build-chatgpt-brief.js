#!/usr/bin/env node

/**
 * Assemble the one brief to paste into ChatGPT.
 *
 * Two files are maintained, because they change for different reasons:
 * chatgpt-instructions.md is how to record a resource and changes when the
 * schema does; chatgpt-daily-search.md is what to look for and changes when
 * the coverage does. Splitting them keeps a schema edit from forcing a rewrite
 * of the search strategy.
 *
 * Pasting two things is a worse job than pasting one, though, and the moment
 * there are two there is a chance only one gets updated. So this joins them
 * into a single block rather than anyone keeping a third copy by hand -- the
 * exact drift this project has spent its time undoing everywhere else.
 *
 *     node scripts/build-chatgpt-brief.js
 */

const fs = require('fs');
const path = require('path');

const DIR = __dirname;
const OUT = path.join(DIR, 'chatgpt-brief.md');

const PARTS = [
  ['How to record a resource', 'chatgpt-instructions.md'],
  ['What to go looking for', 'chatgpt-daily-search.md'],
];

/** The single fenced block in a source file -- the part meant for ChatGPT. */
function promptOf(file) {
  const text = fs.readFileSync(path.join(DIR, file), 'utf8');
  const fences = [...text.matchAll(/^```$/gm)];
  if (fences.length !== 2) {
    throw new Error(`${file} has ${fences.length} fence lines; expected exactly 2`);
  }
  const body = text.slice(fences[0].index + 4, fences[1].index).trim();
  if (!body) throw new Error(`${file} has an empty prompt block`);
  return body;
}

const sections = PARTS.map(([title, file]) => {
  const rule = '='.repeat(74);
  return `${rule}\n${title.toUpperCase()}\n${rule}\n\n${promptOf(file)}`;
});

fs.writeFileSync(OUT, `# Village Notes — the whole brief for ChatGPT

Everything ChatGPT needs, in one block. Paste all of it into the project
instructions for the assistant that researches and adds resources.

**Generated — do not edit this file.** It is assembled from
\`chatgpt-instructions.md\` and \`chatgpt-daily-search.md\`, which are the ones
to change. Re-run \`node scripts/build-chatgpt-brief.js\` afterwards.

\`\`\`
${sections.join('\n\n\n')}
\`\`\`
`, 'utf8');

const lines = fs.readFileSync(OUT, 'utf8').split('\n').length;
console.log(`Wrote ${path.relative(process.cwd(), OUT)} (${lines} lines) from ${PARTS.length} sources.`);
